export function getChapterTeaching(bookId, chapter, category) {
    const key = `${bookId}:${chapter}`;
    if (CURATED[key]) {
        return {
            teaching_en: CURATED[key].en.message,
            teaching_why_en: CURATED[key].en.why,
            teaching_af: CURATED[key].af.message,
            teaching_why_af: CURATED[key].af.why,
        };
    }

    const fallback = CATEGORY_TEACHING[category] || CATEGORY_TEACHING.pentateuch;
    return {
        teaching_en: fallback.en.message,
        teaching_why_en: fallback.en.why,
        teaching_af: fallback.af.message,
        teaching_why_af: fallback.af.why,
    };
}
